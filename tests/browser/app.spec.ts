import { test, expect } from '@playwright/test';
import type { Bundle } from '../../src/data';
const appPath=(route:string)=>process.env.APP_PAGES?`/nuestra-ia/#${route}`:route;
test('Panorama, filtros exactos, ficha enlazable y regreso con selección', async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(appPath('/'));
  await expect(page.getByRole('heading',{name:/La inteligencia artificial/})).toBeVisible();
  await page.getByRole('button',{name:'Pausar panel automático'}).click();
  await page.screenshot({path:'test-results/panorama-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Provincia',exact:true}).click();
  await expect(page.getByText(/iniciativas de alcance nacional/, {exact:false}).first()).toBeVisible();
  await page.getByRole('link',{name:'Casuística',exact:true}).click();
  await page.getByLabel('País',{exact:true}).selectOption('Argentina');
  await expect(page).toHaveURL(/pais=Argentina/);
  await page.getByLabel('Ámbito',{exact:true}).selectOption('educacion');
  await expect(page).toHaveURL(/ambito=educacion/);
  const first=page.locator('.case-card').first();const title=await first.getByRole('heading').innerText();await first.click();
  await expect(page.getByRole('heading',{level:1})).toHaveText(title);
  await expect(page.getByRole('heading',{name:'Evidencias y fuentes documentales'})).toBeVisible();
  await page.reload();await expect(page.getByRole('heading',{level:1})).toHaveText(title);
  await page.getByRole('link',{name:'Volver a la casuística'}).click();
  await expect(page).toHaveURL(/pais=Argentina/);await expect(page.getByLabel('Ámbito',{exact:true})).toHaveValue('educacion');
  await page.getByLabel('Buscar casos').fill('zzzzninguncaso');
  await expect(page.getByRole('heading',{name:'No hay casos con estos criterios'})).toBeVisible();
  await page.getByRole('button',{name:'Limpiar todos los filtros'}).click();
  await expect(page.getByLabel('Buscar casos')).toHaveValue('');
  expect(errors).toEqual([]);
});
test('Comparaciones enlazan a los registros y la app funciona en móvil sin desborde', async({page})=>{
  await page.goto(appPath('/comparaciones?escala=provincia&alcance=nacional&dimension=tecnologias'));
  await expect(page.getByRole('heading',{name:'Territorios, usos y preguntas'})).toBeVisible();
  await expect(page).not.toHaveURL(/escala=|alcance=|dimension=/);
  await expect(page.getByLabel('Escala territorial')).toHaveCount(0);
  await expect(page.getByLabel('Localización documentada')).toHaveCount(0);
  await expect(page.locator('.matrix')).toHaveCount(3);
  await expect(page.getByRole('region',{name:'Países × ámbitos'}).locator('tbody tr')).toHaveCount(3);
  await expect(page.getByRole('region',{name:'Países × riesgos'})).toBeVisible();
  await expect(page.getByRole('region',{name:'Países × promesas'})).toBeVisible();
  const bundle:Bundle=await (await page.request.get(process.env.APP_PAGES?'/nuestra-ia/data/corpus.json':'/data/corpus.json')).json();
  const argentina=bundle.casos.filter(c=>c.territorios.some(t=>t.pais==='Argentina')).length;
  const argentinaRow=page.getByRole('region',{name:'Países × ámbitos'}).locator('tbody tr').filter({has:page.getByRole('rowheader',{name:'Argentina',exact:true})});
  await expect(argentinaRow.locator('td').first()).toHaveText(new RegExp(`^${argentina} /`));
  expect(await page.getByRole('region',{name:'Países × riesgos'}).locator('tbody a').first().getAttribute('href')).toContain('riesgo=');
  expect(await page.getByRole('region',{name:'Países × promesas'}).locator('tbody a').first().getAttribute('href')).toContain('promesa=');
  await page.locator('.matrix tbody a').first().click();
  await expect(page).toHaveURL(/\/casos\?/);await expect(page.locator('.case-card').first()).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  for(const route of ['/','/casos','/comparaciones','/proyecto']) {
    await page.goto(appPath(route));await expect(page.getByRole('heading',{level:1})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),route).toBe(true);
  }
  await page.getByRole('link',{name:'Referencias',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Referencias',exact:true})).toBeVisible();
  await page.reload();await expect(page.getByRole('heading',{name:'Referencias',exact:true})).toBeVisible();
  await page.goto(appPath('/casos/NO-EXISTE'));await expect(page.getByRole('heading',{name:'No encontramos este caso'})).toBeVisible();
});
